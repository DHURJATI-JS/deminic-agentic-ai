export function icon(name, cls = 'w-4 h-4', extra = '') {
  const inner = P[name] || P['sparkles'];
  return `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" ${extra}>${inner}</svg>`;
}

export function hydrate(root = document) {
  for (const el of root.querySelectorAll('i[data-icon]')) {
    const svg = document.createElement('span');
    svg.innerHTML = icon(el.dataset.icon, el.getAttribute('class') || 'w-4 h-4');
    el.replaceWith(svg.firstElementChild);
  }
}

// ------------------------------------------------------------------ glyph / emoji upgrader
const GLYPHS = {
  '▶': 'play', '📁': 'folder-plus', '＋': 'file-plus', '⬆': 'upload', '↻': 'refresh',
  '↷': 'redo', '↶': 'undo', '✉️': 'mail', '✉': 'mail', '📍': 'map-pin',
  '📞': 'phone', '🎂': 'cake', '💬': 'message', '📅': 'calendar',
  '💰': 'wallet', '📈': 'trending-up', '🛡️': 'shield-check', '🐙': 'github',
  '🧠': 'brain', '🎬': 'film', '🎵': 'music', '👥': 'users', '⏰': 'bell',
  '⚖️': 'scale', '🌐': 'globe', '🖼️': 'image', '📄': 'file',
};
const KEYS = Object.keys(GLYPHS).sort((a, b) => b.length - a.length);
const SKIP = '.md, pre, code, .CodeMirror, textarea, input, select, [contenteditable], .no-icon-upgrade, svg, #term-out';

function upgradeTextNode(node) {
  const text = node.nodeValue;
  const lead = text.match(/^\s*/)[0].length;
  const rest = text.slice(lead);
  const key = KEYS.find((k) => rest.startsWith(k));
  if (!key) return;
  const parent = node.parentElement;
  if (!parent || parent.closest(SKIP)) return;
  const after = rest.slice(key.length);
  const onlyGlyph = !after.trim() && parent.childNodes.length === 1 && /^(BUTTON|A|SPAN)$/.test(parent.tagName);
  const span = document.createElement('span');
  span.innerHTML = icon(GLYPHS[key], onlyGlyph ? 'w-4 h-4' : 'icon-inline');
  const svg = span.firstElementChild;
  node.nodeValue = text.slice(0, lead);
  node.after(svg, document.createTextNode(after.replace(/^️/, '')));
}

function upgrade(root) {
  if (!(root instanceof Element) || root.closest(SKIP)) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.nodeValue && n.nodeValue.trim() && !(n.parentElement && n.parentElement.closest(SKIP))
      ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT),
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) upgradeTextNode(n);
  hydrate(root);
}

export function installIconUpgrader(...roots) {
  const pending = new Set();
  let scheduled = false;
  const flush = () => { scheduled = false; for (const r of pending) upgrade(r); pending.clear(); };
  const obs = new MutationObserver((muts) => {
    for (const m of muts) for (const n of m.addedNodes) if (n.nodeType === 1 && !n.closest(SKIP)) pending.add(n);
    if (pending.size && !scheduled) { scheduled = true; requestAnimationFrame(flush); }
  });
  for (const r of roots) if (r) { upgrade(r); obs.observe(r, { childList: true, subtree: true }); }
  return obs;
}
