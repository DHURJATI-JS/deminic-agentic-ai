"""Template for the locustfile generated per stress-test run.

User input never becomes code: the paths list is embedded with repr() of a
JSON string (a plain string literal) and parsed with json.loads at runtime.
"""

TEMPLATE = '''# Generated by Deminic for stress-test run {run_id}. Do not edit.
import json
import random

from locust import HttpUser, between, task

PATHS = json.loads({paths_literal})
METHOD = {method_literal}


class SiteVisitor(HttpUser):
    wait_time = between({wait_min}, {wait_max})

    @task
    def visit(self):
        path = random.choice(PATHS)
        if METHOD == "HEAD":
            self.client.head(path, name=path)
        else:
            self.client.get(path, name=path)
'''


def render(run_id: int, paths: list[str], method: str = "GET", wait_min: float = 0.5, wait_max: float = 2.0) -> str:
    import json

    return TEMPLATE.format(
        run_id=int(run_id),
        paths_literal=repr(json.dumps(paths)),
        method_literal=repr("HEAD" if method == "HEAD" else "GET"),
        wait_min=float(wait_min),
        wait_max=float(wait_max),
    )
